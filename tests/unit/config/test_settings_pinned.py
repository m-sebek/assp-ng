@pytest.mark.parametrize(("key", "default", "level"), PINNED, ids=[p[0] for p in PINNED])
def test_setting_is_pinned(key: str, default: object, level: Level) -> None:
    setting = REGISTRY.get(key)
    assert (setting.default, setting.level) == (default, level)
