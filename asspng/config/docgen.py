"""Generated configuration texts: the default.toml template and the reference document."""
from __future__ import annotations

import textwrap
from typing import Any

import tomlkit

from asspng.config.registry import Level, Registry, Setting

_WIDTH = 78
_POLICY = (Level.RECIPIENT, Level.SENDER)


def toml_value(value: Any) -> str:
    """Render a built-in default as a TOML value."""
    return str(tomlkit.item(value).as_string())


def _constraints(s: Setting) -> str:
    parts: list[str] = []
    if s.choices is not None:
        parts.append("one of " + ", ".join(s.choices))
    if s.minimum is not None and s.maximum is not None:
        parts.append(f"{s.minimum:g} to {s.maximum:g}")
    elif s.minimum is not None:
        parts.append(f"at least {s.minimum:g}")
    elif s.maximum is not None:
        parts.append(f"at most {s.maximum:g}")
    if s.non_empty:
        parts.append("not empty")
    return "; ".join(parts)


def render_default_toml(registry: Registry) -> str:
    """A default.toml with every policy setting present, commented out and documented."""
    settings = [s for s in registry.all() if s.level in _POLICY]
    # Top-level keys must come before the first table header to stay top-level.
    settings.sort(key=lambda s: "." in s.key)
    lines = [
        "# ASSP-NG default policy (generated by 'assp-ng config init').",
        "#",
        "# Every setting is shown commented out with its built-in default. Uncomment a line",
        "# to change it; keep only values that differ from the default. Per-domain and",
        "# per-mailbox overrides live in domain.d/ and user.d/. Run 'assp-ng config doc'",
        "# for the full reference, and 'assp-ng config check' after editing by hand.",
    ]
    table: str | None = None
    for s in settings:
        parent = s.key.rpartition(".")[0]
        lines.append("")
        if parent and parent != table:
            lines.append(f"# [{parent}]")
        table = parent or table
        lines.extend(textwrap.wrap(s.description, _WIDTH, initial_indent="# ",
                                   subsequent_indent="# "))
        constraint = _constraints(s)
        lines.append(f"# Level: {s.level.value}" + (f". Allowed: {constraint}" if constraint
                                                    else ""))
        lines.append(f"# {s.key.rpartition('.')[2]} = {toml_value(s.default)}")
    return "\n".join(lines) + "\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_reference(registry: Registry) -> str:
    """Markdown reference of every setting; docs/configuration.md is this text."""
    out = [
        "# ASSP-NG configuration reference",
        "",
        "<!-- Generated by 'assp-ng config doc' from the settings registry. Do not edit. -->",
        "",
        "Settings live in layered TOML files in `/etc/assp-ng`. Each setting has a level that "
        "says where it is allowed:",
        "",
        "- `system`: only in `assp-ng.toml`.",
        "- `recipient`: in `default.toml`, `domain.d/<domain>.toml` and "
        "`user.d/<address>.toml`; resolved by the recipient address (mailbox, then domain, "
        "then default, then built-in).",
        "- `sender`: the same files, resolved by the authenticated user name.",
        "",
        "Durations are whole numbers with an optional suffix `s`, `m`, `h` or `d` "
        "(for example `90`, `30s`, `15m`, `24h`, `7d`); a bare number means seconds. "
        "Unknown keys and keys at a level where they are not allowed are errors.",
        "",
        "Besides these values, `assp-ng.toml` holds the `[[listener]]` and "
        "`[[tls.certificate]]` tables. A listener has `name`, `kind` (`smtp`, `submission` or "
        "`submissions`), `port`, `backend` (`host:port`) and optionally `ipv4`, `ipv6`, "
        "`bind4`, `bind6`, `xclient` and `auth`. A listener with `auth = true` needs a "
        "loopback backend host, because the credentials reach the backend in plain text. "
        "A certificate has `name`, `hostnames`, `cert` and `key`.",
        "",
        "| Key | Type | Default | Level | Description |",
        "|---|---|---|---|---|",
    ]
    for s in registry.all():
        description = s.description
        constraint = _constraints(s)
        if constraint:
            description += f" Allowed: {constraint}."
        out.append(f"| `{s.key}` | {s.kind} | `{_cell(toml_value(s.default))}` | "
                   f"{s.level.value} | {_cell(description)} |")
    return "\n".join(out) + "\n"
